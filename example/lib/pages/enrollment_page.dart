import 'dart:math';
import 'package:flutter/material.dart';
import 'package:flutter_bio_auth/flutter_bio_auth.dart';
import 'package:permission_handler/permission_handler.dart';

import 'result_page.dart';

class EnrollmentPage extends StatefulWidget {
  const EnrollmentPage({super.key});

  @override
  State<EnrollmentPage> createState() => _EnrollmentPageState();
}

class _EnrollmentPageState extends State<EnrollmentPage> {
  final TextEditingController _customNameController = TextEditingController();

  late String _autoGeneratedId;
  String _effectiveUserId = '';
  bool _enrolling = false;
  String? _error;

  @override
  void initState() {
    super.initState();
    _regenerateId();
  }

  void _regenerateId() {
    final int timestamp = DateTime.now().millisecondsSinceEpoch;
    final int rand = Random().nextInt(9000) + 1000;
    setState(() {
      _autoGeneratedId =
          'USR_${timestamp.toRadixString(36).toUpperCase()}_$rand';
    });
  }

  @override
  void dispose() {
    _customNameController.dispose();
    super.dispose();
  }

  Future<void> _startEnrollment() async {
    final String custom = _customNameController.text.trim();
    // Concatenate if user entered a custom name/label, otherwise use generated ID directly
    _effectiveUserId =
        custom.isEmpty ? _autoGeneratedId : '${custom}_$_autoGeneratedId';

    final PermissionStatus status = await Permission.camera.request();
    if (!status.isGranted) {
      setState(() => _error = 'Camera permission is required to enroll.');
      return;
    }

    setState(() {
      _enrolling = true;
      _error = null;
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Enroll Face Identity')),
      body: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          children: <Widget>[
            // Auto ID Generation Card
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
              decoration: BoxDecoration(
                color: Theme.of(context)
                    .colorScheme
                    .primaryContainer
                    .withOpacity(0.4),
                borderRadius: BorderRadius.circular(14),
                border: Border.all(
                  color: Theme.of(context).colorScheme.primary.withOpacity(0.3),
                ),
              ),
              child: Row(
                children: <Widget>[
                  Icon(Icons.fingerprint,
                      color: Theme.of(context).colorScheme.primary),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: <Widget>[
                        const Text(
                          'Automatic Unique ID',
                          style: TextStyle(
                              fontSize: 11,
                              fontWeight: FontWeight.w600,
                              color: Colors.grey),
                        ),
                        Text(
                          _autoGeneratedId,
                          style: TextStyle(
                            fontSize: 14,
                            fontWeight: FontWeight.bold,
                            letterSpacing: 0.5,
                            color: Theme.of(context).colorScheme.primary,
                          ),
                        ),
                      ],
                    ),
                  ),
                  if (!_enrolling)
                    IconButton(
                      icon: const Icon(Icons.refresh, size: 20),
                      tooltip: 'Generate new ID',
                      onPressed: _regenerateId,
                    ),
                ],
              ),
            ),
            const SizedBox(height: 12),

            // Optional User Entry Field
            TextField(
              controller: _customNameController,
              enabled: !_enrolling,
              decoration: const InputDecoration(
                labelText: 'User Name / Entry (Optional)',
                hintText: 'e.g. John or Rider_01',
                helperText:
                    'Optional: concatenated with the unique ID automatically',
                border: OutlineInputBorder(),
                prefixIcon: Icon(Icons.person_outline),
              ),
            ),
            if (_error != null) ...<Widget>[
              const SizedBox(height: 8),
              Text(_error!,
                  style: TextStyle(color: Theme.of(context).colorScheme.error)),
            ],
            const SizedBox(height: 16),
            Expanded(
              child: _enrolling
                  ? FaceEnrollmentView(
                      userId: _effectiveUserId,
                      enableLiveness: false,
                      onEnrolled: (FaceEnrollmentResult result) async {
                        if (!mounted) return;
                        setState(() {
                          _enrolling = false;
                          _regenerateId();
                          _customNameController.clear();
                        });
                        final NavigatorState navigator = Navigator.of(context);
                        await navigator.push(
                          MaterialPageRoute<void>(
                            builder: (_) => ResultPage(
                              success: result.success,
                              title: result.success
                                  ? 'Enrollment successful'
                                  : 'Enrollment failed',
                              details: result.success
                                  ? <String, String>{
                                      'Unique ID': result.userId,
                                      'Samples used': '${result.samplesUsed}',
                                      'Duration':
                                          '${result.duration.inMilliseconds} ms',
                                    }
                                  : <String, String>{
                                      'Reason': result.failureReason?.name ??
                                          'unknown',
                                    },
                            ),
                          ),
                        );
                        if (mounted) navigator.pop();
                      },
                      onError: (String err) {
                        if (!mounted) return;
                        setState(() {
                          _enrolling = false;
                          _error = err;
                        });
                      },
                      onClose: () {
                        if (!mounted) return;
                        setState(() => _enrolling = false);
                      },
                    )
                  : Center(
                      child: Column(
                        mainAxisAlignment: MainAxisAlignment.center,
                        children: <Widget>[
                          Icon(Icons.face_retouching_natural,
                              size: 64,
                              color: Theme.of(context)
                                  .colorScheme
                                  .primary
                                  .withOpacity(0.5)),
                          const SizedBox(height: 16),
                          const Text(
                            'Align face inside the oval frame.\nA vibrant green bounding indicator confirms detection.',
                            textAlign: TextAlign.center,
                            style: TextStyle(color: Colors.grey),
                          ),
                        ],
                      ),
                    ),
            ),
            const SizedBox(height: 16),
            FilledButton.icon(
              icon: const Icon(Icons.camera_alt),
              onPressed: _enrolling ? null : _startEnrollment,
              label:
                  Text(_enrolling ? 'Enrolling…' : 'Enroll New Face Identity'),
            ),
          ],
        ),
      ),
    );
  }
}
